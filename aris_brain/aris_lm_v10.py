class BilingualQuantumKernelV2:
    """
    中英双语量子核 v2。
    
    中文: 六书 (形旁+声旁+构造类型+笔画)
    英文: 构词法 (词根+前缀+后缀+字母)
    
    两者在统一 12288D 特征空间中:
      - 0-3071:   中文形旁
      - 3072-5119: 中文声旁+拼音
      - 5120-6143: 中文构造类型
      - 6144-10751: 英文词根+词缀
      - 10752-12287: 英文字母+通用
    """
    
    def __init__(self):
        self._cache: Dict[str, np.ndarray] = {}
    
    def feature(self, text: str) -> np.ndarray:
        if text in self._cache:
            return self._cache[text]
        
        text = text.strip()
        if not text:
            return np.zeros(N_FEATURES, dtype=np.float32)
        
        # 检测语言
        cn = sum(1 for c in text if '\u4e00' <= c <= '\u9fff')
        
        if cn > 0:
            feat = self._cn_feature(text)
        else:
            feat = self._en_feature(text)
        
        norm = np.linalg.norm(feat)
        if norm > 1e-10:
            feat = feat / norm
        
        self._cache[text] = feat
        return feat
    
    def _cn_feature(self, text: str) -> np.ndarray:
        """中文六书特征"""
        feat = np.zeros(N_FEATURES, dtype=np.float32)
        
        for ch in text:
            if '\u4e00' <= ch <= '\u9fff' and ch in C:
                rad, ph, typ, py, strokes = C[ch][:5]
                
                # 1. 形旁 (0-3071)
                if rad in XINGPANG_MAP:
                    s, e = XINGPANG_MAP[rad]
                    center = (s + e) // 2
                    for i in range(s, e):
                        d = abs(i - center)
                        feat[i] += math.exp(-d * d / ((e-s) * 4))
                
                # 2. 声旁/拼音 (3072-5119)
                if ph and ph in C:
                    ph_py = C[ph][3] if len(C[ph]) > 3 else ''
                    if ph_py:
                        self._encode_pinyin(ph_py, feat, 3072, 5120)
                
                # 3. 构造类型 (5120-6143)
                if typ in TYPE_MAP:
                    s, e = TYPE_MAP[typ]
                    feat[s:e] += 0.5
                
                # 4. 笔画
                stroke_idx = 11776 + min(strokes, 100)
                if stroke_idx < N_FEATURES:
                    feat[stroke_idx] += 0.15
                
                # 5. 完整拼音编码
                self._encode_pinyin(py, feat, 3328, 5120)
        
        return feat
    
    def _encode_pinyin(self, py: str, feat: np.ndarray, s_reg: int, e_reg: int):
        """拼音编码到特征区域"""
        if not py:
            return
        py = py.strip().lower()
        
        finals = ['a','ai','an','ang','ao','e','ei','en','eng','er',
                  'i','ia','ian','iang','iao','ie','in','ing','io','iong',
                  'iu','o','ong','ou','u','ua','uai','uan','uang','ue','ui','un','uo','v']
        initials = ['b','p','m','f','d','t','n','l','g','k','h','j','q','x',
                    'zh','ch','sh','r','z','c','s','y','w']
        
        # 提取韵母和声母
        for init in initials:
            if py.startswith(init):
                init_idx = initials.index(init)
                fi = s_reg + init_idx * ((e_reg - s_reg) // len(initials))
                feat[fi:fi+20] = 0.5
                py = py[len(init):]
                break
        
        # 韵母
        for final in finals:
            if py.startswith(final):
                fin_idx = finals.index(final)
                ff = s_reg + len(initials) * 20 + fin_idx * 15
                if ff + 15 < e_reg:
                    feat[ff:ff+15] = 0.5
                break
    
    def _en_feature(self, text: str) -> np.ndarray:
        """英文构词法特征"""
        feat = np.zeros(N_FEATURES, dtype=np.float32)
        words = re.findall(r'[a-zA-Z]+', text.lower())
        
        for word in words:
            # 1. 检查是否已知词及其分解
            if word in EN_DECOMPOSE:
                root, suffix, prefix2, prefix1, meaning = EN_DECOMPOSE[word]
                
                # 前缀 (9216-10560)
                for p in [prefix1, prefix2]:
                    if p and p in EN_ROOT_MAP:
                        s, e, _ = EN_ROOT_MAP[p]
                        feat[s:e] += 0.6
                
                # 词根 (6144-9216)
                for r in [root]:
                    for root_word, (s, e, _) in EN_ROOT_MAP.items():
                        if r.startswith(root_word) or root_word.startswith(r):
                            feat[s:e] += 0.6
                            break
                
                # 后缀 (10752-11664)
                if suffix and suffix in EN_ROOT_MAP:
                    s, e, _ = EN_ROOT_MAP[suffix]
                    feat[s:e] += 0.5
                
                # 中文意思作为跨语言桥 (用Unicode编码)
                for ch in meaning:
                    if '\u4e00' <= ch <= '\u9fff' and ch in C:
                        rad = C[ch][0]
                        if rad in XINGPANG_MAP:
                            s, e = XINGPANG_MAP[rad]
                            feat[s:e] += 0.3  # 跨语言桥!
            else:
                # 2. 未知词: 字母特征 (11664-12287)
                for i, letter in enumerate(word):
                    li = ord(letter) - ord('a')
                    pos_region = 11664 + (i % 5) * 60
                    feat[pos_region + li] += 0.3
                    
                    # 常见字母组合 (digraph)
                    if i < len(word) - 1:
                        digraph = word[i:i+2]
                        dg_idx = (hash(digraph) % 400) + 11900
                        if dg_idx < N_FEATURES:
                            feat[dg_idx] += 0.2
        
        return feat
    
    def kernel(self, x: str, y: str) -> float:
        fx = self.feature(x)
        fy = self.feature(y)
        return max(0.0, float(np.dot(fx, fy)))
    
    def match(self, query: str, candidates: List[str], top_k: int = 3):
        """快速匹配"""
        qf = self.feature(query)
        scored = [(c, float(np.dot(qf, self.feature(c)))) for c in candidates]
        scored.sort(key=lambda x: x[1], reverse=True)
        return scored[:top_k]


